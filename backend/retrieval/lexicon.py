"""Colloquial-to-formal legal lexicon used for query rewriting and rerank features.

Each concept maps everyday phrasing (``patterns``) to the wording statutes actually use
(``formal``/``keywords``) and to the laws that usually govern it (``laws``). These are
retrieval hints only; they never appear in an answer as legal conclusions.
"""
from __future__ import annotations

import re
from dataclasses import dataclass, field


@dataclass(frozen=True)
class Concept:
    key: str
    label: str
    patterns: tuple[str, ...]
    formal: tuple[str, ...]
    keywords: tuple[str, ...]
    laws: tuple[str, ...]
    _compiled: tuple[re.Pattern[str], ...] = field(init=False, repr=False, compare=False)

    def __post_init__(self) -> None:
        object.__setattr__(self, "_compiled", tuple(re.compile(p, re.I) for p in self.patterns))

    def search(self, text: str) -> re.Match[str] | None:
        for pattern in self._compiled:
            match = pattern.search(text)
            if match:
                return match
        return None


def _c(key, label, patterns, formal, keywords, laws) -> Concept:
    return Concept(key, label, tuple(patterns), tuple(formal), tuple(keywords), tuple(laws))


